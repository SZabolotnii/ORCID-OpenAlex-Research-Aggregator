"Abstract. The digital transformation of research administration in higher education institutions "
"is hindered by the fragmentation of scientometric data across ORCID, Scopus, Web of Science, and "
"other databases. Inconsistent identifiers, transliterations, and metadata generate duplicate records in "
"institutional reporting, and preparing that reporting requires substantial manual verification. "
"The aim of the article is to substantiate an ICT-based model of proactive research management in "
"a higher education institution, in which the trustworthiness of primary data is ensured by a "
"deterministic consolidation mechanism, and to evaluate that mechanism experimentally. We propose "
"ResearchIQ, a multi-tenant web application whose data-processing core is the Golden Record: an "
"entity-resolution pipeline with metadata canonicalisation that correctly handles Cyrillic titles, "
"pairwise record matching, a guard against false merges, provenance, and a human review band. The "
"architecture follows the TRACE engineering framework: the deterministic core, classical machine "
"learning, and the language model are separated into distinct layers. The quantitative evaluation "
"covers the deterministic consolidation core implemented in executable code; the agent layer is "
"presented as an architectural solution and a prototype natural-language interface that is not "
"evaluated empirically in this work and takes no part in computing the reported metrics. The "
"evaluation uses a reproducible synthetic benchmark modelling a Ukrainian institution (300 academic "
"staff, 20 departments) with no personal data; statistical stability is assessed by Monte Carlo "
"simulation (K=30). The Golden Record reaches an F1 of 76.8 % against 59.7 % for DOI-only and "
"53.5 % for Title+Year; a sensitivity analysis confirms that the result is robust to the choice of "
"thresholds and feature weights. A normaliser defect that destroyed Ukrainian-language publication "
"titles has been fixed. The results position the approach as a realistic strategy for the digital "
"transformation of research administration, with the transfer of the evaluation to real "
"institutional data identified as the next stage."
