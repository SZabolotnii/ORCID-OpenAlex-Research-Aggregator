def add_table(doc, rows, title):
    p = doc.add_paragraph()
    r = p.add_run(title)
    r.bold = True
    t = doc.add_table(rows=len(rows) + 1, cols=5)
    t.style = "Table Grid"
    hdr = ["№", "Зауваження рецензента", "Виконано / не виконано", "Що змінено в рукописі", "Розділ"]
    for i, h in enumerate(hdr):
        cell = t.cell(0, i)
        cell.text = ""
        run = cell.paragraphs[0].add_run(h)
        run.bold = True
        run.font.size = Pt(10)
    for i, (comment, status, what, where) in enumerate(rows, 1):
        for j, val in enumerate([str(i), comment, status, what, where]):
            cell = t.cell(i, j)
            cell.text = ""
            run = cell.paragraphs[0].add_run(val)
            run.font.size = Pt(10)
            if j == 2:
                run.bold = True
    widths = [Cm(0.8), Cm(5.0), Cm(2.4), Cm(8.5), Cm(3.0)]
    for row in t.rows:
        for cell, w in zip(row.cells, widths):
            cell.width = w
    doc.add_paragraph()


